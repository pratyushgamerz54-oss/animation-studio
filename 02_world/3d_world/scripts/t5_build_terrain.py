def tile(key, coll, skirt, vres):
    D = np.load(os.path.join(DATA, f'{key}.npz'))
    z = D['z']; MA, MB, MC = D['MA'], D['MB'], D['MC']
    t = TD[key]
    hdir = wk.P(FOLDER, 'heightfields_v002')
    H = tk.img_float(f'HF_{key}_height', z, os.path.join(hdir, f'{key}_height.exr'))
    packs = {'MA': np.stack([MA[..., 0], MA[..., 1], MA[..., 2]], -1), 'MB': np.stack([MA[..., 3], MB[..., 0], MB[..., 1]], -1),
             'MC': np.stack([MB[..., 2], MB[..., 3], MC[..., 0]], -1), 'MD': np.stack([MC[..., 1], MC[..., 2], MC[..., 3]], -1)}
    imgs = {k: tk.img_rgb(f'HF_{key}_{k}', v, os.path.join(hdir, f'{key}_{k}.png')) for k, v in packs.items()}
    me = bpy.data.meshes.new(f'T5_TERRAIN_{key}')
    o = bpy.data.objects.new(f'T5_TERRAIN_{key}', me); coll.objects.link(o)
    md = o.modifiers.new('HEIGHTFIELD', 'NODES'); md.node_group = HF
    kw = {'Height': H, 'Min X': float(t['x0']), 'Max X': float(t['x1']), 'Min Y': float(t['y0']), 'Max Y': float(t['y1']),
          'Viewport Resolution': float(vres), 'Render Resolution': 1.0, 'Skirt Depth': float(skirt), 'Material': MAT['MAT_T5_TERRAIN']}
    for k, im in imgs.items():
        kw[f'Mask {k}'] = im
    for i, h in enumerate(t['holes'][:2]):
        r = TD[h]
        kw[f'Hole {i + 1} Min'] = (float(r['x0']), float(r['y0']), -1e7); kw[f'Hole {i + 1} Max'] = (float(r['x1']), float(r['y1']), 1e7)
    tk.set_mod(md, **kw)
    st = next(s for s in PREP['tiles'] if s['tile'] == key)
    wk.add_props(o, status=STATUS, tile=key, spacing_m=t['sp'], rect_m=[t['x0'], t['x1'], t['y0'], t['y1']], holes=json.dumps(t['holes']),
                 verts=int(z.size), z_min=st['z_min'], z_max=st['z_max'], detail_rms_m=st['detail_rms_m'],
                 heightfield=f'//heightfields_v002/{key}_height.exr (32-bit float, metres a.s.l.)',
                 note='real mesh generated by NG_T5_HEIGHTFIELD; apply the modifier for a static mesh')
    INFO['tiles'][key] = dict(object=o.name, grid=list(z.shape), spacing_m=t['sp'], viewport_res=vres, skirt_m=skirt)
    return o


def scatter(name, terrain, coll, near=None, mid=None, far=None, **p):
    me = bpy.data.meshes.new(name); o = bpy.data.objects.new(name, me); coll.objects.link(o)
    md = o.modifiers.new('SCATTER', 'NODES'); md.node_group = SC
    kw = dict(Terrain=terrain)
    for k, c in (('Near', near), ('Mid', mid), ('Far', far)):
        if c:
            kw[k] = LIB[c]
    kw.update(p)
    tk.set_mod(md, **{k: (float(v) if isinstance(v, (int, float)) and k != 'Seed' else v) for k, v in kw.items()})
    wk.add_props(o, status=STATUS, terrain=terrain.name, near=near or '', mid=mid or '', far=far or '',
                 params=json.dumps({k: v for k, v in p.items()}))
    INFO['scatter'][name] = dict(terrain=terrain.name, near=near, mid=mid, far=far, **p)
    return o


